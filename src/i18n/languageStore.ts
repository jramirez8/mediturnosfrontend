const dictionaries: Record<AppLanguage, Dictionary> = { es, en, pt };

function normalizeLanguage(value?: string | null): AppLanguage {
  return value === 'en' || value === 'pt' ? value : 'es';
}

type LanguageState = {
  language: AppLanguage;
  hydrated: boolean;
  setLanguage: (language: AppLanguage) => Promise<void>;
  toggleLanguage: () => Promise<void>;
  loadLanguage: () => Promise<void>;
  t: (key: string, params?: Record<string, string | number>) => string;
};

function interpolate(text: string, params?: Record<string, string | number>) {
  if (!params) return text;
  return Object.entries(params).reduce((acc, [key, value]) => acc.split(`{${key}}`).join(String(value)), text);
}

function nextLanguageFrom(current: AppLanguage): AppLanguage {
  if (current === 'es') return 'en';
  if (current === 'en') return 'pt';
  return 'es';
}

export const useLanguageStore = create<LanguageState>((set, get) => ({
  language: 'es',
  hydrated: false,

  setLanguage: async (language) => {
    await storage.setItem(LANGUAGE_KEY, language);
    set({ language, hydrated: true });
  },

  toggleLanguage: async () => {
    const current = get().language;
    await get().setLanguage(nextLanguageFrom(current));
  },

  loadLanguage: async () => {
    const saved = normalizeLanguage(await storage.getItem(LANGUAGE_KEY));
    set({ language: saved, hydrated: true });
  },

  t: (key, params) => {
    const language = get().language;
    const text = dictionaries[language][key] ?? dictionaries.es[key] ?? key;
    return interpolate(text, params);
  },
}));

